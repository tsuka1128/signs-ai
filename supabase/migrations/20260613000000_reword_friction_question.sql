-- 設問4（friction）を肯定形に言い換え、全設問「5=良い」に統一する
--
-- 背景：
--   他の10問は「〜できましたか？／〜届いていましたか？」と肯定形（5=良い）で揃っているが、
--   friction の設問のみ「取られすぎていませんか？」と否定形で、回答者が
--   「5=取られすぎ（悪い）」と解釈し得る逆転項目になっていた。
--   レーダー（意思決定・実行テーマ＝speed+frictionの平均）やAI分析の体温平均で
--   符号が混ざり集計が壊れるため、肯定形に統一する。
--
-- 旧: 「調整」や「根回し」に時間を取られすぎていませんか？
-- 新: 「調整」や「根回し」に時間を奪われず、本来の仕事に向き合えましたか？
--
-- 対象は標準設問（company_id IS NULL）の friction 1問のみ。冪等。
UPDATE survey_questions
SET text = '「調整」や「根回し」に時間を奪われず、本来の仕事に向き合えましたか？'
WHERE company_id IS NULL
  AND category = 'friction';
