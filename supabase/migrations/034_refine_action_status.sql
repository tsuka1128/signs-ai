- **なぜ今か**: （根拠データとユーザーの過去判断との関連）
- **具体策**: （行動レベルの提案）
- **担当の目安**: （役割）
- **期待効果**: （1文）

## 模範出力例（省略）

## 品質基準
- 過去に「採用しない」とされた施策と類似した提案は絶対に行わない。
- 「キープ」されている施策については、再提案するか、そのリソースを他へ回す代替案を出す。
- 数値根拠を必須とする。'::text)
WHERE key = 'ai_action_proposal_prompt';
