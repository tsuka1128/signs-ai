  - 実行する（accepted）: ユーザーが採用し実行中。
  - 採用しない（rejected）: ユーザーが拒否。同タイプのアプローチを嫌う傾向にあると判断する。
  - キープする（kept）: 重要性は認めているが、今は実行できない状態。
  - 完了（completed）: 実行済み。

## 出力フォーマット（3〜5件）
