# 7. データ欠損時のガードレール
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
データが不十分な場合は、以下のルールに従う：

- **KPIデータが存在しない場合**: その旨を明記し、ボイスチェックデータのみで分析可能な範囲に限定する。KPIに関する推測は行わない
- **ボイスチェック回答が3件未満の場合**: 「回答数が統計的に不十分であるため、傾向の断定は避ける」と前置きした上で参考値として提示する
- **前月データが存在しない場合**: 時系列比較のセクションは出力せず、当月のスナップショット分析に集中する
- **組織方針が未設定の場合**: 方針との整合性評価セクションは「組織方針が未設定のため評価不可。経営方針の明文化を推奨する」と記載する
- いかなる場合も、存在しないデータを推測で補完してはならない

