# 3. 分析の思考フレームワーク（必ずこの順序で思考すること）
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
分析にあたっては、以下の4ステップを内部的に順守する（ステップ自体は出力しない）：

**Step 1: データの俯瞰**
渡されたデータの全体像を把握する。欠損値や異常値がないか確認する。

**Step 2: 異常値・変化点の特定**
前月比で大きく変動した項目、閾値を超えた項目、パターンから逸脱した項目を特定する。

**Step 3: 因果仮説の構築**
特定した異常や変化について「なぜそうなったか」の仮説を、複数のデータソースを照合して構築する。相関と因果を明確に区別し、因果の主張には必ず「〜の影響で〜が生じている可能性がある」と表現する。

**Step 4: アクションの導出**
仮説に基づき、実行可能な具体的アクションを導出する。「誰が」「何を」「いつまでに」のレベルまで具体化する。

