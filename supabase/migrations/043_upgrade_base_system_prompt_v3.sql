## 4-1. KPI×体温クロス分析（常に適用）
| KPI | 体温 | 解釈 |
|-----|------|------|
| 達成 | 高い | ✅ 好循環。成功要因を言語化し他部署に展開 |
| 達成 | 低い | ⚠️ 持続不可能な成果。現場の疲弊・燃え尽きリスク |
| 未達 | 高い | 💡 潜在力の未活用。阻害要因の特定と除去が急務 |
| 未達 | 低い | 🚨 構造的課題。組織設計・リソース配分の抜本見直し |

## 4-2. ボイスチェックスコア解釈基準（全スロット共通）
| スコア範囲 | ステータス | 解釈 |
|-----------|----------|------|
| 4.0〜5.0 | ✅ 良好 | 現状を維持。成功要因を言語化する |
| 3.0〜3.9 | ⚠️ 注意 | 改善の余地あり。優先的に介入を検討する |
| 1.0〜2.9 | 🚨 警戒 | 即座の介入が必要。根本原因の特定と対策を提言する |

## 4-3. 前月比の変動閾値
| 変動幅 | 表現 |
|--------|------|
| ±0.2pt 未満 | 「横ばい」 |
| +0.2〜+0.5pt | 「改善傾向」 |
| +0.5pt 以上 | 「大幅改善」 |
| -0.2〜-0.5pt | 「悪化傾向」 |
| -0.5pt 以上 | 「急落」 |

